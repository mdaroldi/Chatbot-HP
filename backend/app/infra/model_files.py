"""Pinned, verified embedding model files (ADR 0006).

`models.toml` is the model allowlist: each model is pinned to a hub repository, a
full commit SHA and the SHA-256 of every file fastembed loads. Files are hashed on
every build, from the cache or after a download, and the models are then loaded from
that verified folder, so what runs is exactly what was hashed. This lives in infra,
not ingestion, because the backend loads the same files to embed queries (Phase 2).
"""

import asyncio
import hashlib
import json
import logging
import tomllib
from collections.abc import Iterable, Mapping, Sequence
from pathlib import Path
from typing import Protocol, cast

import huggingface_hub

from app.domain.ingestion import (
    ModelDownloadError,
    ModelFiles,
    ModelIntegrityError,
    ModelNotAllowedError,
    ModelPinsError,
    VerifiedModel,
)

MODEL_PINS = Path(__file__).resolve().parents[2] / "models.toml"
# huggingface-hub sends metadata requests without a timeout unless given one.
HUB_TIMEOUT_SECONDS = 30.0

logger = logging.getLogger(__name__)

_KEYS = ("name", "source", "revision", "files")
_HEADER = """\
# Embedding model allowlist (ADR 0006): the only models ingestion may download and load.
# Each model is pinned to a hub revision and the SHA-256 of every file fastembed loads.
# Generated by `make model-pins`; review the diff and the model licenses before committing.
"""

# ------------------------------------------------------------------ pins file


def _model(raw: object, position: int) -> ModelFiles:
    where = f"models[{position}]"
    if not isinstance(raw, dict):
        raise ModelPinsError(f"{where} must be a table")
    for key in _KEYS:
        if key not in raw:
            raise ModelPinsError(f"{where} missing key: {key}")
    for key in ("name", "source", "revision"):
        if not isinstance(raw[key], str):
            raise ModelPinsError(f"{where} {key} must be a string")
    unknown = sorted(set(raw) - set(_KEYS))
    if unknown:
        raise ModelPinsError(f"{where} unknown key: {', '.join(unknown)}")
    files = raw["files"]
    if not isinstance(files, dict) or not all(isinstance(v, str) for v in files.values()):
        raise ModelPinsError(f"{where} files must be a table of strings")
    try:
        return ModelFiles(raw["name"], raw["source"], raw["revision"], files)
    except ValueError as exc:
        raise ModelPinsError(f"{where} {exc}") from exc


def parse_pins(text: str) -> dict[str, ModelFiles]:
    """Fail on anything unexpected: the pins are an allowlist, like the corpus manifest."""
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        raise ModelPinsError(f"model pins are not valid TOML: {exc}") from exc
    unknown = sorted(set(data) - {"models"})
    if unknown:
        raise ModelPinsError(f"unknown top-level key: {', '.join(unknown)}")
    raw_models = data.get("models")
    if not isinstance(raw_models, list) or not raw_models:
        raise ModelPinsError("model pins need at least one model")
    pins: dict[str, ModelFiles] = {}
    for position, raw in enumerate(raw_models):
        model = _model(raw, position)
        if model.name in pins:
            raise ModelPinsError(f"duplicate name: {model.name}")
        pins[model.name] = model
    return pins


def load_pins(path: Path = MODEL_PINS) -> dict[str, ModelFiles]:
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise ModelPinsError(f"cannot read model pins {path}") from exc
    return parse_pins(text)


def render_pins(models: Sequence[ModelFiles]) -> str:
    """The whole file, so `make model-pins` output is reproducible and diffs stay small."""
    quote = json.dumps  # a JSON string is a valid TOML basic string
    blocks = [
        "\n".join(
            [
                "[[models]]",
                f"name = {quote(model.name)}",
                f"source = {quote(model.source)}",
                f"revision = {quote(model.revision)}",
                "",
                "[models.files]",
                *(f"{quote(path)} = {quote(sha)}" for path, sha in sorted(model.files.items())),
            ]
        )
        for model in models
    ]
    return _HEADER + "\n" + "\n\n".join(blocks) + "\n"


# ------------------------------------------------------------------ files on disk


def snapshot_dir(cache_dir: Path, source: str, revision: str) -> Path:
    """Where the hub cache keeps one revision of a repository."""
    return cache_dir / f"models--{source.replace('/', '--')}" / "snapshots" / revision


def _sha256(path: Path) -> str | None:
    try:
        with path.open("rb") as stream:
            return hashlib.file_digest(stream, "sha256").hexdigest()
    except FileNotFoundError:
        return None


def hash_files(directory: Path, files: Iterable[str]) -> dict[str, str | None]:
    """SHA-256 of each file's content (following the cache's symlinks); None if absent."""
    return {name: _sha256(directory / name) for name in files}


def _mismatch(pin: ModelFiles, digests: Mapping[str, str | None]) -> str | None:
    return next((name for name in sorted(pin.files) if digests[name] != pin.files[name]), None)


def _verified(pin: ModelFiles, digests: Mapping[str, str | None], folder: Path) -> VerifiedModel:
    # The digests just computed, not the pins: the build records what it hashed.
    computed = {name: digest for name, digest in digests.items() if digest is not None}
    return VerifiedModel(ModelFiles(pin.name, pin.source, pin.revision, computed), folder)


# ------------------------------------------------------------------ hub


class HubClient(Protocol):
    def download(
        self, source: str, revision: str, files: Sequence[str], cache_dir: Path, *, force: bool
    ) -> Path: ...


class SnapshotDownload(Protocol):
    def __call__(  # noqa: PLR0913 - mirrors the keywords of huggingface_hub.snapshot_download
        self,
        repo_id: str,
        *,
        revision: str | None,
        allow_patterns: list[str] | str | None,
        cache_dir: str | Path | None,
        force_download: bool,
        token: bool | str | None,
    ) -> object: ...


class RepoInfo(Protocol):
    @property
    def sha(self) -> str | None: ...


class HubApi(Protocol):
    def model_info(
        self, repo_id: str, *, timeout: float | None = ..., token: bool | str | None = ...
    ) -> RepoInfo: ...

    def list_repo_files(
        self, repo_id: str, *, revision: str | None = ..., token: bool | str | None = ...
    ) -> list[str]: ...


class HuggingFaceHub:
    """The Hugging Face hub, always anonymous (`token=False`) and always at a given revision.

    The functions are injectable so unit tests check the requests without network.
    """

    def __init__(
        self,
        *,
        snapshot: SnapshotDownload = huggingface_hub.snapshot_download,
        api: HubApi = huggingface_hub,
    ) -> None:
        self._snapshot, self._api = snapshot, api

    def download(
        self, source: str, revision: str, files: Sequence[str], cache_dir: Path, *, force: bool
    ) -> Path:
        result = self._snapshot(
            repo_id=source,
            revision=revision,
            allow_patterns=list(files),
            cache_dir=str(cache_dir),
            force_download=force,
            token=False,
        )
        return Path(cast(str, result))  # a list only in dry-run mode, which is never used

    def current_revision(self, source: str) -> str:
        sha = self._api.model_info(source, timeout=HUB_TIMEOUT_SECONDS, token=False).sha
        if sha is None:
            raise ModelDownloadError(f"{source}: the hub reported no revision")
        return sha

    def list_files(self, source: str, revision: str) -> list[str]:
        return sorted(self._api.list_repo_files(source, revision=revision, token=False))


# ------------------------------------------------------------------ source


class PinnedModelSource:
    """ModelSource over the pins: only pinned repositories, only pinned revisions.

    A verified cache needs no network. A cache that does not match triggers one
    forced download (a plain one would keep the bad file); a second mismatch is a
    ModelIntegrityError, a hub failure a ModelDownloadError.
    """

    def __init__(self, pins: Mapping[str, ModelFiles], cache_dir: Path, hub: HubClient) -> None:
        self._pins, self._cache_dir, self._hub = pins, cache_dir, hub

    async def fetch(self, name: str) -> VerifiedModel:
        pin = self._pins.get(name)
        if pin is None:
            raise ModelNotAllowedError(f"{name} has no pin in {MODEL_PINS.name}")
        files = sorted(pin.files)
        folder = snapshot_dir(self._cache_dir, pin.source, pin.revision)
        digests = await asyncio.to_thread(hash_files, folder, files)
        bad = _mismatch(pin, digests)
        if bad is None:
            return _verified(pin, digests, folder)
        force = folder.exists()
        if force:
            logger.warning(
                "cached model files do not match their pins; downloading again",
                extra={"model": name, "file": bad},
            )
        try:
            folder = await asyncio.to_thread(
                self._hub.download, pin.source, pin.revision, files, self._cache_dir, force=force
            )
        except Exception as exc:
            where = f"{pin.source}@{pin.revision}"
            raise ModelDownloadError(f"{name}: cannot download {where}") from exc
        digests = await asyncio.to_thread(hash_files, folder, files)
        bad = _mismatch(pin, digests)
        if bad is not None:
            raise ModelIntegrityError(name, bad, expected=pin.files[bad], actual=digests[bad])
        return _verified(pin, digests, folder)
