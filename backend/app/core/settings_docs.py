"""Markdown reference of the settings, generated so the README cannot drift."""

from enum import Enum

from app.core.settings import Settings

README_START = "<!-- settings-table:start (generated by `make docs-config`) -->"
README_END = "<!-- settings-table:end -->"


def _render_default(value: object) -> str:
    if isinstance(value, Enum):
        value = value.value
    if isinstance(value, bool):
        value = str(value).lower()
    if isinstance(value, list):
        value = ",".join(str(item) for item in value)
    return f"`{value}`"


def settings_markdown_table() -> str:
    """One row per environment variable, in declaration order, with its default."""
    rows = ["| Variable | Default | Description |", "|---|---|---|"]
    for name, field in Settings.model_fields.items():
        default = "*required*" if field.is_required() else _render_default(field.default)
        rows.append(f"| `{name.upper()}` | {default} | {field.description} |")
    return "\n".join(rows) + "\n"
