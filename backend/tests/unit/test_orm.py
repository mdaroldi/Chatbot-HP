"""Behavior of the declarative base and its constraint naming convention."""

from sqlalchemy import CheckConstraint, Column, ForeignKey, Integer, MetaData, String, Table
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from app.infra.orm import NAMING_CONVENTION, Base

# SQLAlchemy's dialect constructor is unannotated.
POSTGRES = postgresql.dialect()  # type: ignore[no-untyped-call]

EXPECTED_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


def test_naming_convention_is_pinned() -> None:
    assert dict(NAMING_CONVENTION) == EXPECTED_CONVENTION
    assert dict(Base.metadata.naming_convention).items() >= EXPECTED_CONVENTION.items()


def test_convention_produces_deterministic_constraint_names() -> None:
    """Named constraints are what make autogenerated downgrades reliable."""
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    Table("parent", metadata, Column("id", Integer, primary_key=True))
    child = Table(
        "child",
        metadata,
        Column("id", Integer, primary_key=True),
        Column("parent_id", ForeignKey("parent.id")),
        Column("email", String(100), unique=True, index=True),
        Column("age", Integer),
        CheckConstraint("age >= 0", name="age_non_negative"),
    )

    ddl = str(CreateTable(child).compile(dialect=POSTGRES))
    index_ddl = [str(CreateIndex(index).compile(dialect=POSTGRES)) for index in child.indexes]

    assert "CONSTRAINT pk_child PRIMARY KEY" in ddl
    assert "CONSTRAINT fk_child_parent_id_parent FOREIGN KEY" in ddl
    assert "CONSTRAINT ck_child_age_non_negative CHECK" in ddl
    assert index_ddl == ["CREATE UNIQUE INDEX ix_child_email ON child (email)"]


def test_no_tables_are_mapped_yet() -> None:
    """Phase 0 schema is empty; the baseline migration must match it."""
    assert Base.metadata.tables == {}
